    /**
     * Abre o formulario com os dados da categoria. Ao salvar, copia os campos para o objeto.
     *
     * @return true se o usuario confirmou
     */
    public boolean editar(Categoria categoria) {
        setTitle(categoria.getId() == null ? "Cadastrar categoria" : "Editar categoria");
        txtId.setText(categoria.getId() == null ? "" : String.valueOf(categoria.getId()));
        txtNome.setText(categoria.getNome() == null ? "" : categoria.getNome());
        setLocationRelativeTo(getParent());
        setVisible(true);
        if (confirmado) {
            categoria.setNome(txtNome.getText().trim());
        }
        return confirmado;
    }

