    /**
     * Abre o formulario com os dados de motorista. Ao salvar, copia os campos para o objeto.
     *
     * @return true se o usuario confirmou
     */
    public boolean editar(Motorista motorista) {
        setTitle(motorista.getId() == null ? "Cadastrar motorista" : "Editar motorista");
        txtId.setText(motorista.getId() == null ? "" : String.valueOf(motorista.getId()));
        txtNome.setText(motorista.getNome() == null ? "" : motorista.getNome());
        txtTelefone.setText(motorista.getTelefone() == null ? "" : motorista.getTelefone());
        setLocationRelativeTo(getParent());
        setVisible(true);
        if (confirmado) {
            motorista.setNome(txtNome.getText().trim());
            motorista.setTelefone(txtTelefone.getText().trim());
        }
        return confirmado;
    }

